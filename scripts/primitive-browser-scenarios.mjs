import assert from 'node:assert/strict'

export async function runPrimitiveScenarios({command,evaluate,until,click,aria,input,key,screenshot}) {
  const snapshot=()=>evaluate(`JSON.parse(document.querySelector('.editor-diagnostics').dataset.snapshot)`)
  const status=()=>evaluate(`(()=>{const d=document.querySelector('.editor-diagnostics').dataset;return {revision:d.revision,history:d.history}})()`)
  const ghost=()=>evaluate(`JSON.parse(document.querySelector('.primitive-action-diagnostics').dataset.snapshot)`)
  const valid=value=>until(`document.querySelector('.primitive-action-diagnostics')?.dataset.valid==='${value}'`)
  const absent=()=>until(`!document.querySelector('.primitive-action-panel')`)
  async function vector(field,values){for(let i=0;i<3;i++)await input(aria(`Primitive ${field} ${'XYZ'[i]}`),String(values[i]))}
  async function begin(kind){await click(aria('Primitive tools'));await click(aria(`Build ${kind}`));await until(`document.querySelector('.primitive-action-panel')`)}
  await command('Emulation.setDeviceMetricsOverride',{width:1500,height:1000,deviceScaleFactor:1,mobile:false})
  await click(aria('Architecture workspace'));await until(`document.querySelector('.editor-workspace')?.dataset.editorReady==='true'`)
  await click('.document-actions > button[title="Save current draft, then create a new document"]')
  await until(`document.querySelector('.editor-diagnostics').dataset.blocks==='0'`)
  const original=await snapshot(),initial=await status()
  await begin('line');await vector('start',[0,0,0]);await vector('end',[2,0,0]);await valid(true)
  const line=await ghost();assert.equal(line.cells.length,3)
  await screenshot('primitive-line-desktop')
  await click(aria('Confirm primitive action'));await absent()
  assert.deepEqual((await snapshot()).cells,line.cells)
  assert.equal(Number((await status()).history),Number(initial.history)+1)
  const committed=await snapshot(),committedStatus=await status()
  await begin('line');await vector('start',[0,0,0]);await vector('end',[2,0,0]);await valid(false)
  await click(aria('Cancel primitive action'));await absent()
  assert.deepEqual(await snapshot(),committed);assert.deepEqual(await status(),committedStatus)
  await click(aria('Undo editor'));await until(`document.querySelector('.editor-diagnostics').dataset.blocks==='0'`)
  await click(aria('Redo editor'));await until(`document.querySelector('.editor-diagnostics').dataset.blocks==='3'`)
  await click(aria('Frame editor scene'))
  await click(aria('Undo editor'));await until(`document.querySelector('.editor-diagnostics').dataset.blocks==='0'`)
  for(const [kind,end,count] of [['plane',[2,0,2],9],['solid box',[2,2,2],27],['hollow box',[2,2,2],26]]){
    const before=await status()
    await begin(kind);await vector('start',[0,0,0]);await vector('end',end);await valid(true)
    const candidate=await ghost();assert.equal(candidate.cells.length,count)
    assert.deepEqual(await snapshot(),original);assert.deepEqual(await status(),before)
    await input(aria('Primitive end X'),'30000000');await valid(false)
    assert.equal(await evaluate(`document.querySelector('[aria-label="Confirm primitive action"]').disabled`),true)
    await vector('end',end);await valid(true)
    await evaluate(`document.querySelector('[aria-label="Primitive end Z"]').focus()`);await key('Enter','Enter');await absent()
    assert.deepEqual((await snapshot()).cells,candidate.cells)
    await click(aria('Undo editor'));await until(`document.querySelector('.editor-diagnostics').dataset.blocks==='0'`)
  }
  await begin('line');await vector('end',[2,1,0]);await valid(false)
  const beforeCancel=await status()
  await click(aria('Cancel primitive action'));await absent();assert.deepEqual(await status(),beforeCancel)
  await begin('plane');await vector('end',[2,2,2]);await valid(false)
  await evaluate(`document.querySelector('canvas').focus()`);await key('Escape','Escape');await absent()
  // Native pointer stages the endpoint without committing.
  await begin('plane');await vector('start',[0,0,0]);await click(aria('Editor Y view'))
  await evaluate('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))')
  const point=await evaluate(`(()=>{const m=JSON.parse(document.querySelector('canvas').dataset.editorCamera).projection,p=[2.5,0,2.5],q=[0,0,0,0];for(let r=0;r<4;r++)q[r]=m[r]*p[0]+m[4+r]*p[1]+m[8+r]*p[2]+m[12+r];const b=document.querySelector('canvas').getBoundingClientRect();return {x:b.x+(q[0]/q[3]+1)*b.width/2,y:b.y+(1-q[1]/q[3])*b.height/2}})()`)
  await command('Input.dispatchMouseEvent',{type:'mouseMoved',...point})
  for(const type of ['mousePressed','mouseReleased'])await command('Input.dispatchMouseEvent',{type,...point,button:'left',buttons:type==='mousePressed'?1:0,clickCount:1})
  await valid(true);assert.deepEqual(await snapshot(),original)
  assert.notEqual(await evaluate(`document.querySelector('[aria-label="Primitive end X"]').value`),'0')
  await command('Emulation.setDeviceMetricsOverride',{width:620,height:900,deviceScaleFactor:1,mobile:false})
  await screenshot('primitive-plane-compact')
  assert.equal(await evaluate(`(()=>{const p=document.querySelector('.primitive-action-panel'),b=p.getBoundingClientRect();return b.left>=0&&b.right<=innerWidth&&b.bottom<=innerHeight&&p.contains(document.elementFromPoint(b.left+b.width/2,b.top+b.height/2))})()`),true)
  await click(aria('Cancel primitive action'));await absent()
  await command('Emulation.setDeviceMetricsOverride',{width:1500,height:1000,deviceScaleFactor:1,mobile:false})
  if(!await evaluate(`!!document.querySelector('.editor-library')`))await click(aria('Toggle editor library'))
  await input(aria('Search resources'),'minecraft:red_bed');await click('.resource-item[title="minecraft:red_bed"]')
  await begin('line');await vector('start',[0,0,0]);await vector('end',[2,0,0]);await valid(true)
  const beds=await ghost();assert.equal(beds.cells.length,6)
  assert.equal(beds.cells.filter(cell=>cell.state.properties.part==='head').length,3)
  await click(aria('Confirm primitive action'));await absent();assert.deepEqual((await snapshot()).cells,beds.cells)
  await click(aria('Undo editor'));await until(`document.querySelector('.editor-diagnostics').dataset.blocks==='0'`)
  await begin('line');await vector('start',[0,0,0]);await vector('end',[0,0,2]);await valid(false)
  await click(aria('Cancel primitive action'));await absent()
  await input(aria('Search resources'),'minecraft:oak_log');await click('.resource-item[title="minecraft:oak_log"]')
  await begin('line');await click(aria('Component Editor workspace'));await absent()
  await click(aria('3D Preview workspace'));assert.equal(await evaluate(`!!document.querySelector('[aria-label="Primitive tools"]')`),false)
  console.log('primitiveBuildResult: passed')
}
