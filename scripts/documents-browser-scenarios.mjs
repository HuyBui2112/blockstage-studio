import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'

export async function runDocumentScenarios({ command, evaluate, until, click, aria, input, upload, key, screenshot, createPeer, directory }) {
  const current = () => evaluate(`JSON.parse(document.querySelector('.editor-diagnostics').dataset.snapshot)`)
  const ready = `document.querySelector('.editor-workspace')?.dataset.editorReady==='true'`
  const settle = async () => { await evaluate('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))'); await until(ready) }
  const saved = async () => { await evaluate(`Array.from(document.querySelectorAll('.document-actions button')).find(button=>button.textContent.trim()==='Save').click()`); await until(`document.querySelector('.document-saved')`) }
  const newDocument = async () => { await evaluate(`Array.from(document.querySelectorAll('.document-actions button')).find(button=>button.textContent.trim()==='New').click()`); await settle() }
  const rename = async name => {
    await input(aria('Document name'), name)
    await evaluate(`document.querySelector('[aria-label="Document name"]').dispatchEvent(new FocusEvent('focusout',{bubbles:true}))`)
    await settle()
  }
  const manager = async () => { await click(aria('Manage editor documents')); await until(`document.querySelector('.documents-dialog') && document.querySelector('.documents-content')?.getAttribute('aria-busy')==='false'`) }
  const close = () => click(aria('Close Documents'))
  const row = id => `.saved-document[data-document-id=${JSON.stringify(id)}]`
  const remove = id => click(`${row(id)} button[title="Delete saved document"]`)
  const confirm = async () => { await click(aria('Confirm document action')); await until(`document.querySelector('.documents-content')?.getAttribute('aria-busy')==='false'`) }
  const raw = async (store, id) => evaluate(`new Promise((resolve,reject)=>{const request=indexedDB.open('blockstage-studio');request.onerror=()=>reject(request.error);request.onsuccess=()=>{const db=request.result,query=db.transaction(${JSON.stringify(store)}).objectStore(${JSON.stringify(store)}).${id === undefined ? 'getAll()' : `get(${JSON.stringify(id)})`};query.onsuccess=()=>{db.close();resolve(query.result??null)};query.onerror=()=>reject(query.error)}})`)
  const reload = async () => {
    const previous = await evaluate('performance.timeOrigin')
    await command('Page.reload')
    await until(`performance.timeOrigin!==${previous} && (${ready})`)
  }
  await click(aria('Architecture workspace'))
  await settle()
  await newDocument()
  const baseline = (await raw('editorDocuments')).map(doc => doc.id).sort(), blank = await current()
  await newDocument(); await newDocument()
  assert.equal((await current()).id, blank.id, 'New on a pristine placeholder must not accumulate IDs or records')
  assert.deepEqual((await raw('editorDocuments')).map(doc => doc.id).sort(), baseline)
  await saved()
  const first = await current()
  assert.ok(await raw('editorDocuments', first.id), 'Explicit Save of an empty document must be respected')
  await newDocument(); await saved()
  const second = await current()
  const sharedName = (await raw('editorDocuments', first.id)).name
  assert.notEqual(first.id, second.id)
  assert.equal((await raw('editorDocuments', second.id)).name, sharedName, 'Fixtures must have duplicate names')
  await manager()
  assert.ok(await evaluate(`Boolean(document.querySelector(${JSON.stringify(row(first.id))}) && document.querySelector(${JSON.stringify(row(second.id))}))`))
  await screenshot('editor-documents')
  await remove(first.id)
  await evaluate(`Array.from(document.querySelectorAll('.document-confirm button')).find(button=>button.textContent==='Cancel').click()`)
  assert.ok(await raw('editorDocuments', first.id), 'Cancelling delete must preserve storage')
  await click(`${row(first.id)} button[title="Rename saved document"]`)
  await input(aria('Saved document name'), 'Archived draft')
  await confirm()
  await until(`!document.querySelector('.document-confirm')`)
  assert.equal((await raw('editorDocuments', first.id)).name, 'Archived draft')
  assert.equal((await raw('preferences', 'editor:architecture')).value, second.id, 'Inactive rename must not change active preference')
  assert.equal((await current()).id, second.id)
  await click(`${row(first.id)} .saved-document-open`)
  await until(`!document.querySelector('.documents-dialog')`)
  assert.equal((await current()).id, first.id, 'Catalogue Open must switch to the selected ID')
  await manager()
  await click(`${row(first.id)} button[title="Rename saved document"]`)
  await input(aria('Saved document name'), 'Active renamed')
  await confirm(); await until(`!document.querySelector('.document-confirm')`); await close()
  assert.equal(await evaluate(`document.querySelector('[aria-label="Document name"]').value`), 'Active renamed')
  assert.ok(await evaluate(`Boolean(document.querySelector('.document-saved'))`), 'Active rename must acknowledge exactly its saved snapshot')
  await evaluate(`document.querySelector('canvas').focus()`); await key('KeyZ', 'z', 2)
  await until(`document.querySelector('.document-dirty')`)
  await manager(); await click(aria('Discard document changes')); await confirm(); await until(`!document.querySelector('.document-confirm')`)
  await click(`${row(second.id)} .saved-document-open`)
  await until(`!document.querySelector('.documents-dialog')`)
  assert.equal((await current()).id, second.id)
  await manager()

  // Fault seam only in the disposable browser profile; never touch user storage.
  await evaluate(`(()=>{const original=IDBObjectStore.prototype.delete;window.__restoreDelete=()=>{IDBObjectStore.prototype.delete=original};IDBObjectStore.prototype.delete=function(id){if(this.name==='editorDocuments'&&id===${JSON.stringify(first.id)})throw new DOMException('Injected delete failure','QuotaExceededError');return original.call(this,id)}})()`)
  try {
    await remove(first.id); await confirm()
    await until(`document.querySelector('.document-manager-error')?.textContent.includes('Injected delete failure')`)
    assert.ok(await raw('editorDocuments', first.id), 'Failed delete must preserve snapshot')
    assert.ok(await evaluate(`Boolean(document.querySelector(${JSON.stringify(row(first.id))}))`), 'Failed delete must preserve catalogue row')
  } finally { await evaluate('window.__restoreDelete();delete window.__restoreDelete') }
  await confirm()
  await until(`!document.querySelector(${JSON.stringify(row(first.id))})`)
  assert.equal(await raw('editorDocuments', first.id), null)
  await close()
  await rename('Pending local changes')
  await manager(); await remove(second.id)
  assert.ok(await evaluate(`document.querySelector('.document-confirm').textContent.includes('unsaved changes')`), 'Active delete must disclose discarded local edits')
  await confirm()
  await until(`!document.querySelector(${JSON.stringify(row(second.id))})`)
  assert.equal(await raw('editorDocuments', second.id), null)
  assert.equal(await raw('preferences', 'editor:architecture'), null)
  await close()
  await evaluate(`document.querySelector('canvas').focus()`); await key('KeyZ', 'z', 2)
  assert.notEqual((await current()).id, second.id, 'Undo editing must not undo document deletion')
  await reload()
  assert.equal((await current()).cells.length, 0, 'Deleted active document must not return after reload')
  assert.equal(await raw('editorDocuments', second.id), null)

  await rename('Scratch only')
  const beforeDiscard = (await raw('editorDocuments')).map(doc => doc.id).sort()
  await manager(); await click(aria('Discard document changes')); await confirm()
  await until(`!document.querySelector('.document-confirm')`)
  await close()
  assert.deepEqual((await raw('editorDocuments')).map(doc => doc.id).sort(), beforeDiscard, 'Discard of unsaved document must not delete Saved records')
  await rename('Saved checkpoint'); await saved()
  const checkpoint = await current()
  await rename('Unsaved rename')
  await manager(); await click(aria('Discard document changes')); await confirm()
  await until(`!document.querySelector('.document-confirm')`)
  await close()
  assert.equal((await current()).id, checkpoint.id)
  assert.equal(await evaluate(`document.querySelector('[aria-label="Document name"]').value`), 'Saved checkpoint')
  assert.ok(await raw('editorDocuments', checkpoint.id), 'Discard must retain base Saved checkpoint')

  const contentPath = join(directory, 'untitled-content.json')
  await writeFile(contentPath, JSON.stringify({ schemaVersion:2,id:'untitled-fixture',name:'Untitled architecture',workspace:'architecture',target:{gameVersion:'26.2',dataVersion:4903},entities:[],objects:[{id:'stone',name:'Stone',kind:'block',cells:[{pos:[0,0,0],state:{name:'minecraft:stone',properties:{}}}],children:[],pivot2:[1,1,1],orientation:0}] }))
  await upload(aria('Import editor document'), contentPath)
  await until(`document.querySelector('.editor-diagnostics').dataset.blocks==='1' && document.querySelector('.document-dirty')`)
  const untitled = await current()
  await newDocument()
  assert.equal(await raw('editorDocuments', untitled.id), null, 'Protecting Untitled content must not silently create a Saved checkpoint')
  const recovery = (await raw('editorDraftHeads')).find(head => head.documentId === untitled.id && head.status === 'live')
  assert.ok(recovery, 'Switch must protect Untitled content as a recovery draft')
  await manager(); await click(aria('Recovery documents'))
  await until(`document.querySelector('.recovery-list')?.getAttribute('aria-busy')==='false'`)
  await click(`.recovery-item[data-recovery-id=${JSON.stringify(recovery.id)}] button[aria-label^="Restore draft"]`)
  await click(aria('Confirm recovery action')); await until(`!document.querySelector('.documents-dialog')`)
  assert.equal((await current()).cells[0].state.name, 'minecraft:stone')
  await newDocument()

  // Editor documents and reusable component assets have independent lifetimes/IDs.
  await click(aria('Component Editor workspace')); await settle()
  const assets = await raw('componentAssets'), asset = assets[0]
  assert.ok(asset, 'Existing workflow must provide a reusable component')
  if (!await evaluate(`Boolean(document.querySelector('.editor-library'))`)) await click(aria('Toggle editor library'))
  await evaluate(`Array.from(document.querySelectorAll('.editor-library-tabs button')).find(button=>button.textContent.startsWith('Components')).click()`)
  const editAsset = async () => {
    await evaluate(`(()=>{const card=Array.from(document.querySelectorAll('.component-asset')).find(card=>card.querySelector('strong').textContent===${JSON.stringify(asset.name)});Array.from(card.querySelectorAll('button')).find(button=>button.textContent==='Edit').click()})()`)
    await settle()
  }
  await editAsset(); await saved()
  const copy = await current()
  assert.notEqual(copy.id, asset.id, 'Working copy must have an independent ID')
  assert.equal((await raw('editorRevisions', copy.id)).componentAssetId, asset.id)
  await manager(); await remove(copy.id); await confirm(); await until(`!document.querySelector('.document-confirm')`); await close()
  assert.deepEqual(await raw('componentAssets', asset.id), asset, 'Document delete must preserve library asset')
  await editAsset(); await saved()
  const replacement = await current()
  assert.notEqual(replacement.id, copy.id, 'Editing library asset after delete must use a fresh working ID')
  await reload()
  await click('.outliner-section button.primary')
  await settle()
  assert.equal((await raw('componentAssets')).length, assets.length, 'Library publication after reload must update the original asset, not create a duplicate')
  assert.ok(await raw('componentAssets', asset.id))

  // Two actual app pages: stale delete conflicts; stale peer Save cannot resurrect.
  await click(aria('Architecture workspace')); await settle()
  await rename('Shared document'); await saved()
  const shared = await current()
  const peer = await createPeer()
  try {
    await peer.evaluate(`document.querySelector('[aria-label="Architecture workspace"]').click()`)
    await peer.until(`document.querySelector('.editor-workspace')?.dataset.editorReady==='true'`)
    await manager(); await remove(shared.id)
    await peer.evaluate(`(()=>{const field=document.querySelector('[aria-label="Document name"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(field,'Peer revision');field.dispatchEvent(new Event('input',{bubbles:true}));field.dispatchEvent(new FocusEvent('focusout',{bubbles:true}))})()`)
    await peer.until(`document.querySelector('[aria-label="Document name"]').defaultValue==='Peer revision'`)
    await peer.evaluate(`Array.from(document.querySelectorAll('.document-actions button')).find(button=>button.textContent.trim()==='Save').click()`)
    await peer.until(`document.querySelector('.document-saved')`)
    await confirm()
    await until(`document.querySelector('.document-manager-error')?.textContent.includes('another session')`)
    assert.equal((await raw('editorDocuments', shared.id)).name, 'Peer revision', 'Stale delete must not remove the peer revision')
    await close(); await reload()
    await manager(); await remove(shared.id); await confirm(); await until(`!document.querySelector('.document-confirm')`)
    await close()
    await peer.evaluate(`(()=>{const field=document.querySelector('[aria-label="Document name"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(field,'Peer stale edits');field.dispatchEvent(new Event('input',{bubbles:true}));field.dispatchEvent(new FocusEvent('focusout',{bubbles:true}))})()`)
    await peer.until(`document.querySelector('[aria-label="Document name"]').defaultValue==='Peer stale edits'`)
    await peer.evaluate(`Array.from(document.querySelectorAll('.document-actions button')).find(button=>button.textContent.trim()==='Save').click()`)
    await peer.until(`document.querySelector('.editor-feedback')?.textContent.includes('another session')`)
    assert.equal(await raw('editorDocuments', shared.id), null, 'Peer Save must not resurrect a deleted document')
    assert.equal(await peer.evaluate(`document.querySelector('[aria-label="Document name"]').value`), 'Peer stale edits', 'Peer conflict must keep local edits')
  } finally { await peer.close() }
  await manager()
  await command('Emulation.setDeviceMetricsOverride', { width: 620, height: 800, deviceScaleFactor: 1, mobile: false })
  assert.ok(await evaluate(`(()=>{const r=document.querySelector('.documents-dialog').getBoundingClientRect();return r.width<=innerWidth&&r.height<=innerHeight})()`), 'Documents must fit compact screen')
  await screenshot('editor-documents-compact')
  await close()
  console.log(JSON.stringify({ documentsResult: 'passed', checks: ['pristine New no Saved spam', 'explicit empty Save', 'same names/different IDs', 'Open/active and inactive rename', 'rename without pointer switch', 'delete cancel/rollback', 'active/inactive delete', 'Undo/reload no resurrection', 'saved and unsaved discard', 'Untitled content preserved on switch', 'component asset identity survives document deletion/reload', 'two app pages stale delete/save conflicts', 'compact manager'] }))
}
