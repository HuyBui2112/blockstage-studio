import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'

/** Native input regression for the B08 copy session; no calls into editor actions. */
export async function runQuickBuildScenarios({ command, evaluate, until, click, aria, input, upload, key, screenshot, directory }) {
  const ready = `document.querySelector('.editor-workspace')?.dataset.editorReady === 'true'`
  const snapshot = () => evaluate(`JSON.parse(document.querySelector('.editor-diagnostics').dataset.snapshot)`)
  const status = () => evaluate(`(() => {const d=document.querySelector('.editor-diagnostics').dataset;return {revision:d.revision,savedRevision:d.savedRevision,history:d.history,future:d.future}})()`)
  const ghost = () => evaluate(`JSON.parse(document.querySelector('.copy-action-diagnostics').dataset.snapshot)`)
  const focus = () => evaluate(`document.querySelector('canvas').focus()`)
  const absent = () => until(`!document.querySelector('.copy-action-panel')`)
  const valid = value => until(`document.querySelector('.copy-action-diagnostics')?.dataset.valid === '${value}'`)
  async function menu(action) {
    await click(aria('Copy tools')); await click(aria(`${action} objects`))
    assert.equal(await evaluate(`document.querySelector('.copy-action-menu').open`), false)
    assert.equal(await evaluate(`document.activeElement === document.querySelector('canvas')`), true)
  }
  async function shortcut(code, value, modifiers) { await focus(); await key(code, value, modifiers) }
  async function vector(prefix, values) { for (let i=0;i<3;i++) await input(aria(`${prefix} ${'XYZ'[i]}`), String(values[i])) }
  async function unchanged(before, state) { assert.deepEqual(await snapshot(), before); assert.deepEqual(await status(), state) }
  const cell = (name, pos, properties) => ({ pos, state:{name:`minecraft:${name}`,properties} })
  const object = (id, kind, cells=[], children=[]) => ({id,name:id,kind,cells,children,pivot2:[1,1,1],orientation:0})
  const group = object('copy-root','group',[],[
    object('nested','group',[],[object('log','block',[cell('oak_log',[0,0,0],{axis:'x'})])]),
    object('bed','multiblock',[cell('red_bed',[1,0,0],{facing:'north',part:'foot',occupied:'false'}),cell('red_bed',[1,0,-1],{facing:'north',part:'head',occupied:'false'})]),
  ])
  const fixture = {schemaVersion:2,id:'quickbuild-browser',name:'Quick build nested fixture',workspace:'architecture',target:{gameVersion:'26.2',dataVersion:4903},objects:[group],entities:[]}
  await command('Emulation.setDeviceMetricsOverride',{width:1500,height:1000,deviceScaleFactor:1,mobile:false})
  await click(aria('Architecture workspace')); await until(ready)
  if (!await evaluate(`Boolean(document.querySelector('.editor-inspector'))`)) await click(aria('Toggle editor inspector'))
  const file=join(directory,'quickbuild-browser.json'); await writeFile(file,JSON.stringify(fixture))
  await upload(aria('Import editor document'),file)
  await until(`document.querySelector('[aria-label="Document name"]').value === '${fixture.name}'`)
  await click(aria('Select tool')); await click(aria('Frame editor scene'))
  await click('.outliner-object > button')
  await until(`document.querySelector('.editor-diagnostics').dataset.selection === '["copy-root"]'`)
  const original=await snapshot(), initial=await status()
  await menu('Copy'); await unchanged(original,initial)
  // Inputs retain native clipboard shortcuts and never start a copy session.
  await click(aria('Document name'))
  assert.equal(await evaluate(`(()=>{const field=document.querySelector('[aria-label="Document name"]');field.focus();return ['KeyC','KeyV'].every(code=>field.dispatchEvent(new KeyboardEvent('keydown',{code,key:code.slice(-1).toLowerCase(),ctrlKey:true,bubbles:true,cancelable:true})))})()`),true,'Typing fields must retain native clipboard shortcuts')
  assert.equal(await evaluate(`Boolean(document.querySelector('.copy-action-panel'))`),false)
  await shortcut('KeyD','D',8); await until(`document.querySelector('[aria-label="Duplicate preview"]')`)
  await vector('Copy offset',[0,0,0]); await valid(false)
  assert.equal(await evaluate(`document.querySelector('[aria-label="Confirm copy action"]').disabled`),true)
  await shortcut('Enter','Enter'); await unchanged(original,initial)
  await vector('Copy offset',[4,0,0]); await valid(true)
  const rotated=await ghost(); await shortcut('KeyR','r'); assert.deepEqual(await ghost(),rotated)
  await screenshot('quickbuild-duplicate-desktop')
  // Project a real world point, then use native pointer input to stage a target.
  await click(aria('Editor Y view'))
  await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
  const point=await evaluate(`(() => {const m=JSON.parse(document.querySelector('canvas').dataset.editorCamera).projection,p=[3.5,0,2.5],q=[0,0,0,0];for(let r=0;r<4;r++)q[r]=m[r]*p[0]+m[4+r]*p[1]+m[8+r]*p[2]+m[12+r];const b=document.querySelector('canvas').getBoundingClientRect();return {x:b.x+(q[0]/q[3]+1)*b.width/2,y:b.y+(1-q[1]/q[3])*b.height/2}})()`)
  await command('Input.dispatchMouseEvent',{type:'mouseMoved',...point})
  for(const type of ['mousePressed','mouseReleased']) await command('Input.dispatchMouseEvent',{type,...point,button:'left',buttons:type==='mousePressed'?1:0,clickCount:1})
  await unchanged(original,initial)
  assert.ok(await evaluate(`Boolean(document.querySelector('[aria-label="Duplicate preview"]'))`),'Canvas click stages without committing')
  assert.notEqual(await evaluate(`document.querySelector('[aria-label="Copy offset X"]').value`),'4','Native pointer must actually change the staged offset')
  await shortcut('Escape','Escape'); await absent(); await unchanged(original,initial)
  await menu('Duplicate'); await vector('Copy offset',[4,0,0]); await valid(true)
  await evaluate(`document.querySelector('[aria-label="Cancel copy action"]').focus()`)
  assert.equal(await evaluate(`document.activeElement?.getAttribute('aria-label')`),'Cancel copy action')
  // Include the char event payload: keydown alone tests JS handlers but does not activate native buttons.
  for(const type of ['keyDown','keyUp'])await command('Input.dispatchKeyEvent',{type,code:'Enter',key:'Enter',windowsVirtualKeyCode:13,nativeVirtualKeyCode:13,...(type==='keyDown'?{text:'\r',unmodifiedText:'\r'}:{})})
  await absent();await unchanged(original,initial)
  await menu('Duplicate'); await vector('Copy offset',[4,0,0]); await valid(true)
  const candidate=await ghost()
  await click(aria('Confirm copy action')); await absent()
  assert.equal(await evaluate(`document.activeElement===document.querySelector('canvas')`),true,'Confirm must restore viewport keyboard focus')
  const duplicated=await snapshot()
  assert.deepEqual(duplicated.cells.filter(c=>!original.cells.some(o=>o.owner===c.owner)),candidate.cells)
  assert.equal(Number((await status()).history),Number(initial.history)+1)
  assert.ok(candidate.cells.every(c=>!original.cells.some(o=>o.owner===c.owner)))
  assert.equal(candidate.cells.find(c=>c.state.name==='minecraft:oak_log').state.properties.axis,'x')
  assert.deepEqual(candidate.cells.filter(c=>c.state.name==='minecraft:red_bed').map(c=>c.state.properties.part).sort(),['foot','head'])
  await click(aria('Undo editor')); await until(`document.querySelector('.editor-diagnostics').dataset.blocks === '3'`)
  assert.deepEqual((await snapshot()).cells,original.cells)
  await click(aria('Redo editor')); await until(`document.querySelector('.editor-diagnostics').dataset.blocks === '6'`)
  assert.deepEqual((await snapshot()).cells,duplicated.cells)
  await click(aria('Undo editor')); await until(`document.querySelector('.editor-diagnostics').dataset.blocks === '3'`)
  await click('.outliner-object > button')
  await shortcut('KeyC','c',2)
  await shortcut('KeyV','v',2); await vector('Paste position',[8,0,0]); await valid(true)
  const pasted=await ghost(); await shortcut('Enter','Enter'); await absent()
  assert.deepEqual((await snapshot()).cells.filter(c=>c.pos[0]>=8),pasted.cells)
  await shortcut('KeyV','v',2); await vector('Paste position',[12,0,0]); await valid(true)
  const pastedAgain=await ghost()
  assert.ok(pastedAgain.cells.every(c=>!pasted.cells.some(p=>p.owner===c.owner)),'Each paste allocates fresh nested identities')
  await click(aria('Cancel copy action')); await absent()
  await click('.outliner-object > button')
  await shortcut('KeyD','D',10); await until(`document.querySelector('[aria-label="Repeat preview"]')`)
  await input(aria('Repeat axis'),'x'); await input(aria('Repeat copies'),'2'); await input(aria('Repeat spacing'),'-4'); await valid(true)
  const repeat=await ghost(); assert.equal(repeat.cells.length,6)
  assert.deepEqual([...new Set(repeat.cells.map(c=>c.pos[0]))].sort((a,b)=>a-b),[-8,-7,-4,-3])
  // Existing pasted cells at x=8 make this repeat collide atomically.
  await input(aria('Repeat spacing'),'4'); await valid(false)
  await input(aria('Repeat spacing'),'-4'); await valid(true)
  const negative=await ghost(); assert.equal(negative.cells.length,6)
  assert.ok(negative.cells.every(c=>c.pos[0]<0))
  await input(aria('Repeat spacing'),'0'); await valid(false)
  await input(aria('Repeat spacing'),'-4'); await input(aria('Repeat copies'),'100001'); await valid(false)
  await input(aria('Repeat copies'),'2'); await valid(true)
  const repeatBefore=await snapshot(), repeatHistory=Number((await status()).history), repeatCandidate=await ghost()
  await evaluate(`document.querySelector('[aria-label="Repeat spacing"]').focus()`); await key('Enter','Enter'); await absent()
  assert.deepEqual((await snapshot()).cells.filter(c=>c.pos[0]<0),repeatCandidate.cells)
  assert.equal(Number((await status()).history),repeatHistory+1)
  await click(aria('Undo editor')); assert.deepEqual((await snapshot()).cells,repeatBefore.cells)
  // Pending sessions end at a workspace boundary; the in-memory clipboard survives.
  await menu('Paste'); await click(aria('Component Editor workspace')); await until(ready); await absent()
  // Full suite may have an existing component open. Protect it through New, never assume an empty workspace.
  await evaluate(`Array.from(document.querySelectorAll('.document-actions button')).find(button=>button.textContent.trim()==='New').click()`)
  await until(`(${ready}) && document.querySelector('.editor-diagnostics').dataset.blocks==='0'`)
  await menu('Paste'); await vector('Paste position',[0,0,0]); await valid(true)
  const componentBefore=await snapshot(),componentState=await status()
  await command('Emulation.setDeviceMetricsOverride',{width:620,height:900,deviceScaleFactor:1,mobile:false})
  await screenshot('quickbuild-paste-compact')
  assert.ok(await evaluate(`(()=>{const panel=document.querySelector('.copy-action-panel'),r=panel.getBoundingClientRect();return r.width>=250&&r.left>=0&&r.right<=innerWidth&&document.elementFromPoint(r.left+20,r.top+20)?.closest('.copy-action-panel')===panel})()`),'Compact panel must be visible and unobscured, not merely fit page width')
  assert.ok(await evaluate(`document.documentElement.scrollWidth <= innerWidth + 1`),'Compact copy panel must not cause horizontal page overflow')
  await click(aria('Cancel copy action')); await absent(); await unchanged(componentBefore,componentState)
  await command('Emulation.setDeviceMetricsOverride',{width:1500,height:1000,deviceScaleFactor:1,mobile:false})
  await click(aria('Assets workspace')); await click(aria('Component Editor workspace')); await until(ready)
  await menu('Paste'); await valid(true); await shortcut('Enter','Enter'); await absent()
  assert.equal((await snapshot()).cells.length,3,'Clipboard paste must commit into Component workspace')
  await click(aria('Undo editor')); await until(`document.querySelector('.editor-diagnostics').dataset.blocks==='0'`)
  await click(aria('3D Preview workspace')); await until(ready)
  assert.equal(await evaluate(`Boolean(document.querySelector('[aria-label="Copy tools"]'))`),false)
  await click(aria('Architecture workspace')); await until(ready)
  const fence={...fixture,name:'Copy neighbor fixture',objects:[object('fence','block',[cell('oak_fence',[0,0,0],{north:'false',east:'false',south:'false',west:'false',waterlogged:'false'})])]}
  const fencePath=join(directory,'quickbuild-fence.json');await writeFile(fencePath,JSON.stringify(fence));await upload(aria('Import editor document'),fencePath)
  await until(`document.querySelector('[aria-label="Document name"]').value==='Copy neighbor fixture'`)
  await click('.outliner-object > button');const beforeFence=await snapshot()
  assert.equal(await evaluate(`document.querySelector('[aria-label="Auto connections"]').disabled`),false)
  await click(aria('Auto connections'));await menu('Duplicate');await valid(true)
  const connected=await ghost()
  assert.equal(connected.cells.length,2,'Preview must include the changed existing neighbor')
  assert.equal(connected.cells.find(c=>c.pos[0]===0).state.properties.east,'true')
  assert.equal(connected.cells.find(c=>c.pos[0]===1).state.properties.west,'true')
  await click(aria('Auto connections'));await valid(true);assert.equal((await ghost()).cells.length,1)
  await click(aria('Auto connections'));await valid(true);assert.deepEqual(await ghost(),connected,'Policy changes rebuild the same-ID preview')
  await click(aria('Confirm copy action'));await absent();assert.deepEqual((await snapshot()).cells,connected.cells)
  await click(aria('Undo editor'));assert.deepEqual((await snapshot()).cells,beforeFence.cells)
  await click(aria('Redo editor'));assert.deepEqual((await snapshot()).cells,connected.cells)
  await click(aria('Auto connections'))
  console.log(JSON.stringify({quickBuildResult:'passed',checks:['menu and viewport keyboard shortcuts','copy without document/history mutation','typing field clipboard shortcuts remain native','duplicate cancel/collision/R isolation','native pointer updates staged offset without commit','exact ghost vs commit and atomic Undo/Redo','fresh repeated paste IDs','repeat signed spacing/count/budget/collision and input Enter','workspace cancellation and cross-workspace clipboard commit','clipboard survives Assets workspace','read-only Preview','620px panel visible and unobscured','neighbor policy rebuild and original/new state parity with one Undo/Redo']}))
}
